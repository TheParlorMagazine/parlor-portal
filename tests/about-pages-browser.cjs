const assert = require('node:assert/strict')
const { chromium } = require('/tmp/parlor-tour-validation/node_modules/playwright-core')
const base = process.env.ABOUT_TEST_URL || 'http://127.0.0.1:3107'

;(async () => {
  const browser = await chromium.launch({ executablePath: '/usr/bin/chromium', args: ['--no-sandbox'] })
  try {
    for (const width of [390, 768, 1440]) {
      const context = await browser.newContext({ viewport: { width, height: 1000 }, reducedMotion: 'reduce' })
      const page = await context.newPage(), errors = []
      page.on('pageerror', error => errors.push(error.message))
      await page.route('**/*', route => route.request().url().startsWith(base) ? route.continue() : route.abort())
      await page.goto(`${base}/about/mission`)
      await page.getByRole('heading', { name: /Independent journalism\.\s*Collective possibility\./ }).waitFor()
      await page.waitForFunction(() => document.querySelector('.about-site').style.getPropertyValue('--about-menu-height'))
      assert.equal(await page.locator('.about-home').getAttribute('href'), '/')
      assert.equal(await page.locator('.about-menu [aria-current=page]').innerText(), 'Mission')
      assert.equal(await page.locator('.mission-row').count(), 4)
      assert.equal(await page.locator('#purpose .mission-purpose-image').getAttribute('src'), 'https://res.cloudinary.com/dwytmbczs/image/upload/v1794410362/parlor/articles/file_hgptzh.webp')
      assert.match(await page.locator('#purpose .mission-purpose-figure').evaluate(el => el.previousElementSibling.textContent), /^We approach this work/)
      assert.match(await page.locator('#collective').innerText(), /all work full time/)
      assert.match(await page.locator('#funding').innerText(), /not a nonprofit organization/)
      assert.equal(await page.locator('#funding a[href="https://tinynewsco.org/"]').count(), 2)
      assert.equal(await page.locator('.about-art').evaluate(el => getComputedStyle(el).transform), 'none')
      if (width >= 1000) {
        await page.locator('.mission-index a[href="#funding"]').click()
        await page.waitForFunction(() => document.querySelector('.mission-index a[href="#funding"]').getAttribute('aria-current') === 'location')
        assert.ok(Math.abs((await page.locator('.about-menu-wrap').boundingBox()).y) < 1)
        const height = await page.locator('.about-menu-wrap').evaluate(el => el.offsetHeight)
        assert.ok((await page.locator('#purpose').boundingBox()).height >= 1000 - height - 1)
      } else {
        assert.equal(await page.locator('.mission-index').isVisible(), false)
        await page.getByRole('button', { name: 'Scroll About menu right' }).click()
        await page.waitForFunction(() => document.querySelector('.about-menu').scrollLeft > 0)
        await page.getByRole('button', { name: 'Scroll About menu left' }).waitFor()
      }
      assert.equal(await page.locator('.mission-buttons a[href="/plans"]').count(), 1)
      assert.equal(await page.locator('.mission-buttons a[href="/buy-us-a-birthday-gift"]').count(), 1)
      assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
      await page.goto(`${base}/about/editorial-standards`)
      await page.locator('.standards-intro').waitFor()
      await page.waitForFunction(() => document.querySelector('.about-site').style.getPropertyValue('--about-menu-height'))
      assert.equal(await page.locator('.about-menu [aria-current=page]').innerText(), 'Editorial Standards')
      assert.equal(await page.locator('.standards-intro p').count(), 5)
      assert.match(await page.locator('.submissions-notice').innerText(), /currently closed/)
      assert.equal(await page.locator('.submissions-notice').evaluate(el => getComputedStyle(el).color), 'rgb(132, 54, 76)')
      assert.equal(await page.locator('.standards-intro h2,.standards-intro summary').count(), 0)
      assert.equal(await page.locator('.standards-section').count(), 4)
      assert.equal(await page.locator('details[open]').count(), 0)
      const activeLink = await page.locator('.about-menu [aria-current=page]').boundingBox()
      assert.ok(activeLink.x >= 0 && activeLink.x + activeLink.width <= width)
      const verticals = page.locator('#the-types-of-stories-we-publish')
      await verticals.locator('summary').click()
      assert.equal(await verticals.locator('.section-index a').count(), 4)
      const issueHref = await verticals.getByRole('link', { name: 'Check out our latest issue.' }).getAttribute('href')
      assert.ok(issueHref === '/print' || issueHref.startsWith('/issue/'))
      await verticals.getByRole('link', { name: 'Work & Wealth', exact: true }).click()
      assert.equal(await verticals.evaluate(el => el.open), true)
      assert.equal(await page.locator('.subsection').evaluateAll(elements => elements.every(el => getComputedStyle(el).borderBottomWidth === '0px')), true)
      for (const [id, count] of [['what-we-do-not-publish', 5], ['ai-use-policy', 7]]) {
        const section = page.locator(`#${id}`)
        await section.locator('summary').click()
        assert.equal(await section.locator('li').count(), count)
        assert.equal(await section.locator('.section-index,h3').count(), 0)
        await section.locator('summary').focus()
        await page.keyboard.press('Enter')
        assert.equal(await section.evaluate(el => el.open), false)
      }
      await page.goto(`${base}/about/editorial-standards#the-types-of-stories-we-publish-world-politics`)
      await page.waitForFunction(() => document.getElementById('the-types-of-stories-we-publish').open)
      assert.equal(await page.locator('.site-footer [data-cookie-preferences]').count(), 1)
      assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
      await page.goto(`${base}/about/people`)
      await page.locator('.founding-team-card').last().waitFor()
      assert.equal(await page.locator('.founding-team-card').count(), 2)
      assert.equal(await page.locator('.about-menu [aria-current=page]').innerText(), 'The People of The Parlor')
      for (const [slug, name] of [['lindsey-brock-morales', 'Lindsey Brock Morales'], ['alexandria-turnley', 'Alexandria Turnley']]) {
        const response = await page.goto(`${base}/about/people/${slug}`)
        assert.equal(response.status(), 200)
        await page.locator('.founder-profile h2').waitFor()
        assert.equal(await page.locator('.founder-profile h2').innerText(), name)
        assert.ok((await page.locator('.founder-biography').innerText()).trim().length > 0)
        assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
      }
      assert.match(await page.locator('.founder-biography').innerText(), /Durham Nativity School/)
      const missing = await page.goto(`${base}/about/people/not-a-founder`)
      assert.equal(missing.status(), 404)
      assert.deepEqual(errors, [])
      await context.close()
    }
    const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'no-preference' })
    const page = await context.newPage()
    await page.route('**/*', route => route.request().url().startsWith(base) ? route.continue() : route.abort())
    await page.goto(`${base}/about/mission`)
    await page.waitForFunction(() => document.querySelector('.about-site').classList.contains('about-motion-ready'))
    await page.evaluate(() => scrollTo(0, 250))
    await page.waitForFunction(() => parseFloat(document.querySelector('.about-site').style.getPropertyValue('--about-art-offset')) > 0)
    await context.close()
    console.log('PASS actual production pages at mobile/tablet/desktop: approved Mission content, sticky menus, mobile chevrons, desktop index, native accordions, bullet lists, deep links, reduced motion, parallax, footer consent link, no overflow or runtime errors. External artwork delivery is not exercised.')
  } finally { await browser.close() }
})().catch(error => { console.error(error); process.exitCode = 1 })
